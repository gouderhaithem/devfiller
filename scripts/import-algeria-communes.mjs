// Builds src/profiles/algeria-communes.ts from the open dataset of Algeria's administrative
// divisions: https://github.com/me-yasserzaouag/algeria-wilayas-communes (MIT, © 2026 Yasser
// Zaouag), which follows JO n° 25 of 5 April 2026 (Law 26-06 of 4 April 2026).
//
//   node scripts/import-algeria-communes.mjs path/to/communes.json
//
// Writes algeria-communes.ts (for generated addresses) and algeria-commune-names.ts (for the fill
// engine). Only names are imported: the commune, its daira and its wilaya. Entries without a daira or an
// Arabic name are skipped, and the dataset's post_code values are not used, because they don't
// match Algérie Poste's postal codes.
import { readFileSync, writeFileSync } from 'node:fs';

const source = process.argv[2];
if (!source) { console.error('Usage: node scripts/import-algeria-communes.mjs path/to/communes.json'); process.exit(1); }
const raw = JSON.parse(readFileSync(source, 'utf8'));
const list = Array.isArray(raw) ? raw : raw.communes ?? Object.values(raw);
// NFKC turns the Arabic presentation forms some entries use (ﷲ, ﻻ, ﺳ…) back into ordinary letters, so
// names match what forms write; invisible direction marks are dropped.
const clean = text => String(text ?? '').normalize('NFKC').replace(/[\u200e\u200f\u202a-\u202e]/g, '').replace(/\s+/g, ' ').trim();
// Arabic names the dataset gets wrong: a Kabyle spelling with a Persian letter, and two spellings in
// one field. Keyed by wilaya code and French name.
const ARABIC_FIXES = { '34|Ouled Sidi Brahim': 'أولاد سيدي إبراهيم', '44|Ain Defla': 'عين الدفلى' };
const rows = list
  .map(c => [Number(c.wilaya_code), clean(c.name), clean(c.name_ar), clean(c.daira), clean(c.daira_ar)])
  .map(([code, name, ar, daira, dairaAr]) => [code, name, ARABIC_FIXES[`${code}|${name}`] ?? ar, daira, dairaAr])
  .filter(([code, name, ar, daira, dairaAr]) => code >= 1 && code <= 69 && name && ar && daira && dairaAr)
  .sort((a, b) => a[0] - b[0] || a[1].localeCompare(b[1]));
const skipped = list.length - rows.length;
const body = rows.map(row => `  ${JSON.stringify(row)},`).join('\n');
writeFileSync('src/profiles/algeria-communes.ts', `// Generated by scripts/import-algeria-communes.mjs. Do not edit by hand.
// Source: https://github.com/me-yasserzaouag/algeria-wilayas-communes (MIT, © 2026 Yasser Zaouag),
// following JO n° 25 of 5 April 2026 (Law 26-06). ${rows.length} of ${list.length} communes: ${skipped} without a daira
// or an Arabic name were skipped.
// [wilaya code, commune, commune in Arabic, daira, daira in Arabic]
export const COMMUNES: ReadonlyArray<readonly [number, string, string, string, string]> = [
${body}
];
`);
// The fill engine only needs the names, to recognize a commune list: one compact string.
const names = [...new Set(rows.flatMap(([, name, ar]) => [name, ar]))].join('|');
writeFileSync('src/profiles/algeria-commune-names.ts', `// Generated by scripts/import-algeria-communes.mjs. Do not edit by hand. Same source as
// algeria-communes.ts: the names of its communes in French and Arabic, separated by "|".
export const COMMUNE_NAMES = ${JSON.stringify(names)};
`);
console.log(`Wrote ${rows.length} communes (${skipped} skipped).`);
